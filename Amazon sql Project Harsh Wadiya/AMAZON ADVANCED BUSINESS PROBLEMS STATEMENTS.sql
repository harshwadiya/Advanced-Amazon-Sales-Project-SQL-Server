2. Revenue by Category
Calculate total revenue generated by each product category.
Challenge: Include the percentage contribution of each category to total revenue.
*/

select *,ROUND((Sales_by_category * 100.0 / SUM(Sales_by_category) OVER ()), 2) AS percentage_contributionn from

(select c.category_id,c.category_name,Round(sum(oi.total_sales),2) as Sales_by_category from Category as c
