-- Problem 4
-- Monthly Sales Trend
-- Query monthly total sales over the past year.
-- Challenge: Display the sales trend, grouping by month, return current_month sale, last month sale!


with Monthly_trend as (
select  top 12 Year(o.order_date) as YEAR,
Datename(Month,o.Order_date) as Month,
Month(o.Order_date) as Month_Number,
ROUND(sum(oi.total_sales),2) as Sales_by_Month
from Orders as o
LEFT JOIN Order_items as oi
ON o.order_id = oi.order_id
Group by Year(o.order_date),Month(o.Order_date),Datename(Month,o.Order_date)
Order by Year(o.order_date) desc,Month(o.Order_date)desc,Datename(Month,o.Order_date)desc
)

select *,(select
	top 1 Sales_by_Month from Monthly_trend) Current_month_sales,
	lead(Sales_by_Month,1,null) over(order by year desc) as Last_Month_sales 
from Monthly_trend
;
